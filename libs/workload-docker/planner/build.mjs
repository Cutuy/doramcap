import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { buildSync } from "esbuild";
const root = fileURLToPath(new URL(".", import.meta.url));
const generated = root + "src/generated/";
mkdirSync(generated, { recursive: true });
const args = [
  "--keep-case",
  "-p",
  root + "../proto",
  root + "../proto/planner.proto",
];
execFileSync(root + "node_modules/.bin/pbjs", [
  "-t",
  "json",
  "-o",
  generated + "schema.json",
  ...args,
]);
execFileSync(root + "node_modules/.bin/pbjs", [
  "-t",
  "static-module",
  "-w",
  "es6",
  "--no-service",
  "-o",
  generated + "protocol.js",
  ...args,
]);
execFileSync(root + "node_modules/.bin/pbts", [
  "-o",
  generated + "protocol.d.ts",
  generated + "protocol.js",
]);
const output =
  "/* Generated by build.mjs.\n" +
  readFileSync(root + "THIRD_PARTY_NOTICES.txt", "utf8") +
  "*/\n" +
  buildSync({
    entryPoints: [root + "src/index.ts"],
    bundle: true,
    platform: "neutral",
    format: "iife",
    target: "es2024",
    minify: true,
    legalComments: "none",
    write: false,
  }).outputFiles[0].text;
const destination = root + "bundle.js";
if (process.argv.includes("--check")) {
  if (readFileSync(destination, "utf8") !== output)
    throw new Error("Planner bundle is stale; run npm run build");
} else writeFileSync(destination, output);
